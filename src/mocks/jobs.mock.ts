import type { Job } from '../types/job';

type MockJobInput = Omit<Job, 'source' | 'description' | 'url' | 'company_logo'> & {
  requirements: string[];
  responsibilities: string[];
  benefits: string[];
};

function createMockJob({
  requirements,
  responsibilities,
  benefits,
  ...job
}: MockJobInput): Job {
  const list = (items: string[]) =>
    items.map((item) => `<li>${item}</li>`).join('');

  return {
    ...job,
    source: 'mock',
    company_logo: null,
    url: '',
    description: [
      `<h2>About the role</h2><p>${job.company_name} is looking for a ${job.title} to help build thoughtful, reliable products for a distributed team. You will collaborate across disciplines, make pragmatic decisions, and have room to shape how the team works.</p>`,
      `<h3>Responsibilities</h3><ul>${list(responsibilities)}</ul>`,
      `<h3>What you bring</h3><ul>${list(requirements)}</ul>`,
      `<h3>Benefits</h3><ul>${list(benefits)}</ul>`,
    ].join(''),
  };
}

